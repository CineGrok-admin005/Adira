// Lean voice context for the LinkedIn length-retry call — sliced out of the main
// persona so we never resend the full system prompt on a retry.
export function getLinkedInRetryVoiceContext(): string {
  const wordsStart = ADIRA_SYSTEM_PROMPT.indexOf('## THE WORDS YOU DO NOT USE');
  const wordsEnd = ADIRA_SYSTEM_PROMPT.indexOf('## AUDIENCE');
  const playbookStart = ADIRA_SYSTEM_PROMPT.indexOf('## HOW THE LINKEDIN ALGORITHM WORKS');
  const playbookEnd = ADIRA_SYSTEM_PROMPT.indexOf('## THE 7 DAILY CONTENT PILLARS');

  const words = wordsStart >= 0 && wordsEnd > wordsStart
    ? ADIRA_SYSTEM_PROMPT.slice(wordsStart, wordsEnd).trim() : '';
  const playbook = playbookStart >= 0 && playbookEnd > playbookStart
    ? ADIRA_SYSTEM_PROMPT.slice(playbookStart, playbookEnd).trim() : '';

  const combined = [words, playbook].filter(Boolean).join('\n\n');
  return combined || 'You are ADIRA, CineGrok\'s voice. Write short paragraphs, one idea, first-person, no links in the body.';
}
